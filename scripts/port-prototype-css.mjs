/**
 * Port the novel-mode prototype stylesheet into the product module.
 *
 * The prototype (`docs/prototypes/2026-09-16-novel-mode/novel-mode-workbench.html`)
 * is the design source of truth for the novel-mode front end, so the frame uses
 * its stylesheet verbatim instead of a re-typed approximation. Only the
 * prototype's own chrome — the screen switcher and the staged body it needs —
 * is dropped, and the two selectors that have to bind to the real host instead
 * of a bare document are rewritten:
 *
 *   html[data-theme="night"]  → [data-novel-workbench="frame"][data-nw-theme="night"],
 *                               body[data-ds-dark-theme] [data-novel-workbench="frame"]
 *   html, body { margin: 0 }  → scoped under the frame (the host page owns the document)
 *
 * Usage: node scripts/port-prototype-css.mjs [--check]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const prototypePath = `${root}docs/prototypes/2026-09-16-novel-mode/novel-mode-workbench.html`
const modulePath = `${root}packages/novel-workbench/src/client/workbench-css.ts`

const NIGHT_SELECTOR = '[data-novel-workbench="frame"][data-nw-theme="night"],\nbody[data-ds-dark-theme] [data-novel-workbench="frame"]'

/** Every rewrite the port applies; each one is asserted to have matched. */
const REWRITES = [
  {
    name: 'night theme selector',
    find: 'html[data-theme="night"] {',
    replace: `${NIGHT_SELECTOR} {`,
  },
]

/** Prototype-only chrome: the switcher bar, its chips and the fixed-size stage. */
const PROTOTYPE_CHROME = {
  start: '/* ═══ 原型切换条（不属于产品界面） ═══ */',
  end: '/* ═══ 舞台与应用骨架 ═══ */',
}

function build() {
  const html = readFileSync(prototypePath, 'utf8')
  const styleStart = html.indexOf('<style>')
  const styleEnd = html.indexOf('</style>')
  if (styleStart < 0 || styleEnd < 0) throw new Error('prototype has no single <style> block')
  let css = html.slice(styleStart + '<style>'.length, styleEnd).trim()

  const start = css.indexOf(PROTOTYPE_CHROME.start)
  const end = css.indexOf(PROTOTYPE_CHROME.end)
  if (start < 0 || end < start) throw new Error('prototype chrome markers not found')
  css = `${css.slice(0, start).trimEnd()}\n\n${css.slice(end)}`

  for (const rewrite of REWRITES) {
    if (!css.includes(rewrite.find)) throw new Error(`port rewrite did not match: ${rewrite.name}`)
    css = css.replace(rewrite.find, rewrite.replace)
  }

  // The host owns the document; the application only lays out inside its frame,
  // so the prototype's document-level reset narrows to the frame itself.
  const documentReset = '*, *::before, *::after { box-sizing: border-box; }\nhtml, body { margin: 0; }'
  if (!css.includes(documentReset)) throw new Error('port rewrite did not match: document reset')
  css = css.replace(
    documentReset,
    '*, *::before, *::after { box-sizing: border-box; }\n[data-novel-workbench="frame"] { margin: 0; }',
  )

  // The prototype centers its stage on a demo page; the product frame is the
  // whole window, so the demo's document-level width floor is dropped with it.
  const demoWidthFloor = '@media (max-width: 1279px) { body { min-width: 1280px; } }'
  if (!css.includes(demoWidthFloor)) throw new Error('port rewrite did not match: demo width floor')
  css = css.replace(demoWidthFloor, '')

  if (css.includes('`') || css.includes('${')) throw new Error('css is not embeddable in a template literal')

  return `/**
 * The novel-mode stylesheet, ported verbatim from
 * \`docs/prototypes/2026-09-16-novel-mode/novel-mode-workbench.html\`.
 *
 * Generated by \`scripts/port-prototype-css.mjs\`; edit the prototype first and
 * re-run the generator instead of hand-editing the string. The only changes are
 * the ones the generator lists: the prototype's own screen switcher is dropped,
 * the night selector binds to the frame (or the host's dark theme) instead of a
 * bare document, and the document reset is left to the host page.
 */
export const WORKBENCH_CSS = \`${css.replace(/\\/g, '\\\\').replace(/`/g, '\\`')}\`
`
}

const next = build()
if (process.argv.includes('--check')) {
  const current = readFileSync(modulePath, 'utf8')
  if (current !== next) {
    console.error('workbench-css.ts is stale; run: node scripts/port-prototype-css.mjs')
    process.exit(1)
  }
  console.log('workbench-css.ts matches the prototype')
} else {
  writeFileSync(modulePath, next)
  console.log(`wrote ${modulePath} (${next.length} B)`)
}
